/**
 * Optional: render an explicit Nginx location for the secret admin URL.
 *
 * The sample vhost already proxies unknown paths to Node, so this file is not
 * required for the gate to work. Never prints the secret. Keep the output off git.
 *
 *   node --env-file-if-exists=.env scripts/render-admin-nginx.mjs --output <file>
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { env, evaluateAdminSecretConfig } from '../src/config/env.js';
import { logger } from '../src/lib/logger.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const defaultOutput = path.resolve(__dirname, '../../deploy/nginx/mws-admin-secret.generated.conf');

function readOutputArg(argv) {
  const index = argv.indexOf('--output');
  if (index === -1 || !argv[index + 1]) return defaultOutput;
  return path.resolve(argv[index + 1]);
}

const secretPath = env.adminSecret.path;
const problems = evaluateAdminSecretConfig({
  isProduction: true,
  secretPath,
});
if (problems.length > 0) {
  logger.error('render.admin_nginx_invalid', { problems });
  process.exit(1);
}

const output = readOutputArg(process.argv);
const location = `/${secretPath}`;

const body = `# Generated by server/scripts/render-admin-nginx.mjs
# Optional explicit location. Sample vhost uses @node instead.
# Do not commit this file.

location = ${location} {
    proxy_pass http://127.0.0.1:8787;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
}

location ^~ ${location}/ {
    proxy_pass http://127.0.0.1:8787;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
}
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, body, { encoding: 'utf8', mode: 0o600 });

logger.info('render.admin_nginx_ok', {
  output,
  configured: true,
});
